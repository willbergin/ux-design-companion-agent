#!/usr/bin/env python3
"""Generate harness adapters from one canonical UX Companion source.

Run: python scripts/build.py [--check]
No third-party dependencies. Safe to run on Windows/macOS/Linux.
"""
from __future__ import annotations

import argparse
import difflib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'src' / 'agent.md'
DESC = (
    'UX partner for product teams. Use for Create mode to explore interaction designs and '
    'build accessible prototypes, or Review mode to assess screenshots, UI, information '
    'architecture, usability and user flows with evidence-qualified scores and fixes.'
)
HEADER = '<!-- Generated by scripts/build.py from src/agent.md. Do not edit this copy. -->\n\n'


def skill_text(core: str) -> str:
    return f'---\nname: ux-companion\ndescription: {DESC}\n---\n\n{HEADER}{core}'


def kiro_agent_text(core: str) -> str:
    return f'---\nname: ux-companion\ndescription: >-\n  UX Design Companion custom agent for creating and reviewing UX designs.\ntools: ["read", "write", "web"]\n---\n\n{HEADER}{core}'


def copilot_text(core: str) -> str:
    return (
        '---\nname: UX Design Companion\n'
        'description: Create and review UI/UX prototypes with evidence-led usability, accessibility, '
        'visual, IA and flow guidance.\n---\n\n'
        + HEADER + core
    )


def files(core: str) -> dict[Path, str]:
    result = {}
    for folder in [
        '.agents/skills/ux-companion',      # Codex and Cursor
        '.claude/skills/ux-companion',      # Claude Code
        '.gemini/skills/ux-companion',      # Gemini CLI
        '.kiro/skills/ux-companion',        # Kiro skill
    ]:
        result[ROOT / folder / 'SKILL.md'] = skill_text(core)
    result[ROOT / '.kiro/agents/ux-companion.md'] = kiro_agent_text(core)
    result[ROOT / '.github/agents/ux-companion.agent.md'] = copilot_text(core)
    return result


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='Check adapters without modifying files')
    args = parser.parse_args()
    core = SOURCE.read_text(encoding='utf-8').rstrip() + '\n'
    changes = []
    for path, expected in files(core).items():
        old = path.read_text(encoding='utf-8') if path.exists() else ''
        if old != expected:
            changes.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected, encoding='utf-8')
    if changes:
        print(('Out of sync: ' if args.check else 'Updated: ') + ', '.join(changes))
    else:
        print('All harness adapters are in sync.')
    return int(args.check and bool(changes))


if __name__ == '__main__':
    raise SystemExit(main())
